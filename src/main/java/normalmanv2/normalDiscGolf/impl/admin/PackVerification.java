package normalmanv2.normalDiscGolf.impl.admin;

import javax.net.ssl.HttpsURLConnection;
import java.io.IOException;
import java.net.URI;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;

/** Verifies the served bytes against the pack exported by this instance. */
final class PackVerification {
    private static final int CONNECT_MILLIS = 3000;
    private static final int READ_MILLIS = 3000;
    private static final int MAX_REDIRECTS = 5;
    private static final long DEADLINE_NANOS = 10_000_000_000L;

    record Result(boolean matches, String message) {}

    private PackVerification() {}

    static URI endpoint(String input) {
        URI uri;
        try {
            uri = URI.create(input.strip());
        } catch (IllegalArgumentException invalid) {
            throw new IllegalArgumentException("Enter an HTTPS URL for the exported ZIP.");
        }
        if (!"https".equalsIgnoreCase(uri.getScheme()) || uri.getHost() == null || uri.getUserInfo() != null
                || uri.getFragment() != null || uri.getPort() == 0 || uri.getPort() > 65535)
            throw new IllegalArgumentException("Enter an HTTPS URL for the exported ZIP.");
        return uri;
    }

    static Result check(URI endpoint, Path exported, byte[] expected) {
        HttpsURLConnection connection = null;
        try {
            if (Files.size(exported) != expected.length || !Arrays.equals(Files.readAllBytes(exported), expected))
                return new Result(false, "The local ZIP differs from the pack generated by this server. Restart to export it again.");
            long deadline = System.nanoTime() + DEADLINE_NANOS;
            int status;
            for (int redirects = 0; ; redirects++) {
                if (System.nanoTime() > deadline) return new Result(false, "The HTTPS download took too long.");
                connection = open(endpoint);
                status = connection.getResponseCode();
                if (status != 301 && status != 302 && status != 303 && status != 307 && status != 308) break;
                if (redirects == MAX_REDIRECTS) return new Result(false, "The download redirected too many times.");
                String location = connection.getHeaderField("Location");
                if (location == null || location.isBlank())
                    return new Result(false, "The download returned a redirect without a destination.");
                try {
                    endpoint = endpoint(endpoint.resolve(location).toString());
                } catch (IllegalArgumentException invalid) {
                    return new Result(false, "Every pack download redirect must use HTTPS.");
                }
                connection.disconnect();
                connection = null;
            }
            if (status != 200) return new Result(false, "The download returned HTTP " + status + ".");
            long length = connection.getContentLengthLong();
            if (length >= 0 && length != expected.length) return mismatch();
            try (var remote = connection.getInputStream()) {
                byte[] buffer = new byte[8192];
                int offset = 0;
                while (offset < expected.length) {
                    if (System.nanoTime() > deadline) return new Result(false, "The HTTPS download took too long.");
                    int count = remote.read(buffer, 0, Math.min(buffer.length, expected.length - offset));
                    if (count < 0 || !Arrays.equals(buffer, 0, count, expected, offset, offset + count)) return mismatch();
                    offset += count;
                }
                if (remote.read() != -1) return mismatch();
            }
            return new Result(true, "HTTPS pack matches the exported ZIP byte for byte.");
        } catch (IOException failure) {
            return new Result(false, "Could not verify the HTTPS download. Check the URL, TLS certificate, and export.");
        } finally {
            if (connection != null) connection.disconnect();
        }
    }

    private static HttpsURLConnection open(URI endpoint) throws IOException {
        var connection = (HttpsURLConnection) endpoint.toURL().openConnection();
        connection.setInstanceFollowRedirects(false);
        connection.setConnectTimeout(CONNECT_MILLIS);
        connection.setReadTimeout(READ_MILLIS);
        connection.setUseCaches(false);
        connection.setRequestProperty("Accept-Encoding", "identity");
        return connection;
    }

    private static Result mismatch() {
        return new Result(false, "The HTTPS download differs from the exported ZIP. Upload the latest export.");
    }
}
